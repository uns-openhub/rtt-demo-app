-- Phase 5c: view scoping.
--   scope = 'blank'      → saved from Explore toolbar (no primary attribute)
--   scope = 'attribute'  → saved while viewing a specific attribute (scopedTopic holds the fullTopic)
-- Rationale: a view saved while looking at attribute A is tuned for A's series
-- context — showing it in attribute B's menu and silently layering A's overlays
-- on B gave the wrong data.  Scoping means each attribute's menu shows only
-- views that belong to it; blank Explore shows blank-scope views plus a
-- separate "From attributes" section.
ALTER TABLE public."chart_views"
  ADD COLUMN IF NOT EXISTS scope text NOT NULL DEFAULT 'blank';
ALTER TABLE public."chart_views"
  ADD COLUMN IF NOT EXISTS "scopedTopic" text NULL;

-- Constraint: scope must be one of the two known values.  Added
-- separately so the default + backfill run first.
DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'chart_views_scope_chk'
      AND conrelid = 'public."chart_views"'::regclass
  ) THEN
    ALTER TABLE public."chart_views"
      ADD CONSTRAINT chart_views_scope_chk
        CHECK (scope IN ('blank', 'attribute'));
  END IF;
END $$;

-- Backfill: existing rows are derived from their spec JSON.  Rows whose
-- spec.primary.fullTopic is a string become 'attribute'; everything else
-- stays 'blank' (the DEFAULT).  Idempotent — only touches rows still at
-- the default value, so re-running init.sql doesn't churn later edits.
UPDATE public."chart_views"
SET scope = 'attribute',
    "scopedTopic" = spec->'primary'->>'fullTopic'
WHERE scope = 'blank'
  AND jsonb_typeof(spec->'primary') = 'object'
  AND spec->'primary'->>'fullTopic' IS NOT NULL
  AND length(spec->'primary'->>'fullTopic') > 0;

CREATE INDEX IF NOT EXISTS chart_views_scoped_topic_idx
  ON public."chart_views" ("scopedTopic")
  WHERE "scopedTopic" IS NOT NULL;

