    IF NOT EXISTS (
      SELECT 1
      FROM information_schema.columns
      WHERE table_schema = 'public'
        AND table_name = 'rag_chunks'
        AND column_name = 'embeddingVector'
    ) THEN
      EXECUTE 'ALTER TABLE public."rag_chunks" ADD COLUMN "embeddingVector" vector';
    END IF;

    EXECUTE '
      UPDATE public."rag_chunks"
      SET "embeddingVector" = embedding::text::vector
      WHERE "embeddingVector" IS NULL
        AND embedding IS NOT NULL
        AND jsonb_typeof(embedding) = ''array''
        AND "embeddingDimensions" = jsonb_array_length(embedding)
    ';

    EXECUTE '
      CREATE INDEX IF NOT EXISTS rag_chunks_embedding_vector_model_idx
        ON public."rag_chunks" ("embeddingModel", "embeddingDimensions")
        WHERE "embeddingVector" IS NOT NULL
    ';
  END IF;
END
$$;

