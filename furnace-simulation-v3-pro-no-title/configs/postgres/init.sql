-- === TRIGGER FIRES TABLE ====================================================
-- Stage 4a (Audit log).  Append-only history of trigger fires.
-- Populated by the controller's TriggerFiresRecorder which subscribes
-- to MQTT trigger output topics and persists each parsed uns-kit
-- payload's metadata + value.
--
-- Fields are denormalised (triggerName, kind, outputTopic) so a row
-- survives `DELETE FROM trigger_definitions` — the audit trail
-- shouldn't disappear when an admin deletes the rule.
--
-- `snapshots` is jsonb (only populated for kind='string' fires);
-- `value` is text (handles both numeric and string fires; admins
-- read it back as a string and the UI can numeric-ify when relevant).
