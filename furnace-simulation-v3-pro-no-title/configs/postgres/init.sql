-- Historical cleanup for stale snapshot rows: keep only the newest mapping per
-- source/topic/version, but only when the source identity is known.
WITH ranked_questdb_mappings AS (
  SELECT
    id,
    ROW_NUMBER() OVER (
      PARTITION BY
        "topicPrefix",
        "processName",
        "packageName",
        COALESCE("version", ''),
        COALESCE("dataGroup", ''),
        COALESCE("suffix", '')
      ORDER BY COALESCE("updatedAt", to_timestamp(0)) DESC,
               LENGTH(COALESCE("tablePrefix", '')) DESC,
               LENGTH(COALESCE("tableName", '')) DESC,
               id DESC
    ) AS rn
  FROM public."questdb_mappings"
  WHERE "processName" IS NOT NULL
    AND "packageName" IS NOT NULL
)
DELETE FROM public."questdb_mappings" q
USING ranked_questdb_mappings ranked
WHERE q.id = ranked.id
  AND ranked.rn > 1;

