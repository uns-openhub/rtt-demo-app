-- Optional pgvector extension for RAG/vector search storage. Dedicated
-- production Postgres servers may not have pgvector installed or may require
-- DBA-owned extension creation, so keep this best-effort and let schema init
-- continue without vector support.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM pg_available_extensions
    WHERE name = 'vector'
  ) THEN
    BEGIN
      CREATE EXTENSION IF NOT EXISTS vector;
    EXCEPTION WHEN OTHERS THEN
      RAISE NOTICE 'Skipping vector extension setup: %', SQLERRM;
    END;
  ELSE
    RAISE NOTICE 'Skipping vector extension setup: pgvector is not available in this database image.';
  END IF;
END
$$;

-- Optional Slovenian full-text search configuration for assistant/UNS search.
-- The official Postgres image does not ship Slovenian Hunspell files by
-- default.  When the image provides `slovenian.dict` and `slovenian.affix` in
-- PostgreSQL's tsearch_data directory, this creates `public.uns_slovenian`.
-- Otherwise init continues and the controller falls back to `simple` search.
DO $$
DECLARE
  has_slovenian_dictionary boolean := false;
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_catalog.pg_ts_dict d
    JOIN pg_catalog.pg_namespace n ON n.oid = d.dictnamespace
    WHERE n.nspname = 'public'
      AND d.dictname = 'uns_slovenian_ispell'
  ) THEN
    BEGIN
      CREATE TEXT SEARCH DICTIONARY public.uns_slovenian_ispell (
        TEMPLATE = ispell,
        DictFile = slovenian,
        AffFile = slovenian
      );
      has_slovenian_dictionary := true;
    EXCEPTION WHEN OTHERS THEN
      RAISE NOTICE 'Skipping public.uns_slovenian text search config: %', SQLERRM;
    END;
  ELSE
    has_slovenian_dictionary := true;
  END IF;

  IF has_slovenian_dictionary THEN
    IF NOT EXISTS (
      SELECT 1
      FROM pg_catalog.pg_ts_config c
      JOIN pg_catalog.pg_namespace n ON n.oid = c.cfgnamespace
      WHERE n.nspname = 'public'
        AND c.cfgname = 'uns_slovenian'
    ) THEN
      CREATE TEXT SEARCH CONFIGURATION public.uns_slovenian (COPY = pg_catalog.simple);
    END IF;

    ALTER TEXT SEARCH CONFIGURATION public.uns_slovenian
      ALTER MAPPING FOR asciiword, asciihword, hword_asciipart, word, hword, hword_part
      WITH public.unaccent, public.uns_slovenian_ispell, pg_catalog.simple;
  END IF;
END
$$;

