-- src/triggers/trigger-fires-retention.ts).  Tunable via the
-- TRIGGER_FIRES_RETENTION_DAYS constant in that file.
CREATE TABLE IF NOT EXISTS public."trigger_fires" (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "triggerId" uuid NOT NULL,
  "triggerName" text NOT NULL,
  kind text NOT NULL,
  "outputTopic" text NOT NULL,
  "sourceTopic" text NOT NULL,
  value text NOT NULL,
  uom text NULL,
  "sourceTimestamp" timestamptz NULL,
  "firedAt" timestamptz NOT NULL DEFAULT now(),
  snapshots jsonb NULL
);

-- Hot path: "fires for this trigger, most recent first" (powers the
-- "Recent fires" tab in the trigger Edit dialog).
CREATE INDEX IF NOT EXISTS trigger_fires_trigger_id_fired_at_idx
  ON public."trigger_fires" ("triggerId", "firedAt" DESC);

-- Used by the daily TTL cron to find stale rows quickly.
CREATE INDEX IF NOT EXISTS trigger_fires_fired_at_idx
  ON public."trigger_fires" ("firedAt" DESC);

-- === CAPTURE DEFINITIONS ====================================================
-- Windowed logging automations.  A capture opens when startCondition
-- becomes true, closes when stopCondition becomes true, and emits selected
-- Data attributes as table-shaped UNS rows according to captureConfig.
--
-- Controller owns authoring/persistence; uns-api-global consumes enabled rows
-- from GET /api/captures and owns runtime session execution.
CREATE TABLE IF NOT EXISTS public."capture_definitions" (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  "startCondition" jsonb NOT NULL,
  "stopCondition" jsonb NOT NULL,
  "inputMappings" jsonb NOT NULL,
  "outputTopic" text NOT NULL,
  "captureConfig" jsonb NOT NULL,
  enabled boolean NOT NULL DEFAULT true,
  description text NULL,
  "createdBy" text NULL,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT capture_definitions_start_condition_object_chk
    CHECK (jsonb_typeof("startCondition") = 'object'),
  CONSTRAINT capture_definitions_stop_condition_object_chk
    CHECK (jsonb_typeof("stopCondition") = 'object'),
  CONSTRAINT capture_definitions_input_mappings_array_chk
    CHECK (jsonb_typeof("inputMappings") = 'array'),
  CONSTRAINT capture_definitions_capture_config_object_chk
    CHECK (jsonb_typeof("captureConfig") = 'object')
);

CREATE INDEX IF NOT EXISTS capture_definitions_enabled_idx
  ON public."capture_definitions" (enabled)
  WHERE enabled = true;
CREATE INDEX IF NOT EXISTS capture_definitions_output_topic_idx
  ON public."capture_definitions" ("outputTopic");
CREATE INDEX IF NOT EXISTS capture_definitions_updated_idx
  ON public."capture_definitions" ("updatedAt" DESC);

-- Runtime audit for capture sessions.  Definitions stay controller-owned
